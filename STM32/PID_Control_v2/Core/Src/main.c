double volt2res(float v_sense){
	return (double)((1400.0)*((11.4/v_sense)-1.0));
}

double ntc2temp(double ntc_value){
	double aux,t = 0.0;
	logntc = log(ntc_value);
	log3ntc = logntc * logntc * logntc;

	aux = (0.6876815095e-3 + (2.197912770e-4 * logntc) + (1.217031487e-7 * log3ntc));
	t = ((1.0/aux)-273.0);
	if(t<0)t=0;

	return t;
}

void PID_Init(PID* pid){
	pid->integrator = 0.0f;
	pid->differentiator = 0.0f;
	pid->prevError = 0.0f;
	pid->prevTemp = 0.0f;

	pid->out = 0.0f;

}

double PID_Update(PID* pid, double raw_temp, double setpoint){


	double error = setpoint - raw_temp;

	float proportional = pid->kp * error;


	pid->integrator = pid->integrator + 0.5f * pid->ki * pid->T * (error + pid->prevError);

	if (pid->integrator > pid->limMaxInt) {
		pid->integrator = pid->limMaxInt;

	} else if (pid->integrator < pid->limMinInt) {
		pid->integrator = pid->limMinInt;
	}

    pid->differentiator = -(2.0f * pid->kd * (raw_temp - pid->prevTemp)	/* Note: derivative on measurement, therefore minus sign in front of equation! */
                        + (2.0f * pid->tau - pid->T) * pid->differentiator)
                        / (2.0f * pid->tau + pid->T);

	/*
	* Compute output and apply limits
	*/
    pid->out = proportional + pid->integrator + pid->differentiator;

    if (pid->out > pid->limMax) {

        pid->out = pid->limMax;

    } else if (pid->out < pid->limMin) {

        pid->out = pid->limMin;

    }

	/* Store error and measurement for later use */
    pid->prevError = error;
    pid->prevTemp = raw_temp;

	/* Return controller output */
	return pid->out;
}


